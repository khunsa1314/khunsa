  function getLang() {
    const v = localStorage.getItem("khunsa-lang") || "zh";
    return LANGS.some((l) => l.code === v) ? v : "zh";
  }

  function setLang(code) {
    if (!LANGS.some((l) => l.code === code)) return;
    localStorage.setItem("khunsa-lang", code);
    location.reload();
  }

  function t(key) {
    const pack = UI[getLang()] || UI.zh;
    if (Object.prototype.hasOwnProperty.call(pack, key)) return pack[key];
    return UI.zh[key] != null ? UI.zh[key] : key;
  }

  function format(str, map) {
    return String(str).replace(/\{(\w+)\}/g, (_, k) => (map[k] != null ? map[k] : ""));
  }

  function applyPage() {
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const val = t(el.getAttribute("data-i18n"));
      if (typeof val === "string") el.textContent = val;
    });
    document.querySelectorAll("[data-i18n-html]").forEach((el) => {
      const val = t(el.getAttribute("data-i18n-html"));
      if (typeof val === "string") el.innerHTML = val;
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
    });
    document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
      el.setAttribute("alt", t(el.getAttribute("data-i18n-alt")));
    });
    const titleKey = document.body.getAttribute("data-title");
    if (titleKey === "siteName") document.title = t("siteName");
    else if (titleKey) document.title = t(titleKey) + "｜" + t("siteName");
  }

  const current = LANGS.find((l) => l.code === getLang());
  document.documentElement.lang = current.html;
  document.documentElement.dataset.lang = current.code;

  if (!document.getElementById("khunsa-fonts")) {
    const link = document.createElement("link");
    link.id = "khunsa-fonts";
    link.rel = "stylesheet";
    link.href = "https://fonts.googleapis.com/css2?family=Great+Vibes&family=Noto+Sans+TC:wght@400;500;700&family=Noto+Sans+Thai:wght@400;700&family=Noto+Serif+TC:wght@500;600;700&display=swap";
    document.head.appendChild(link);
  }

  window.KHUNSA_I18N = { LANGS, UI, getLang, setLang, t, format, applyPage };
